'''
WHAT IS THIS DOING?

(Modified) TISE is -1/2 d^2/dx^2 psi + V(x)psi = E psi. Rearranged, this is:
d^2/dx^2 psi = 2*(V(x) - E)*psi

We also replaced d/dx psi with u, giving du/dx = 2*(V(x) - E)*psi(x)

rhs takes in a given psi, u and returns their derivatives: u, 2*(v(x) - E)*psi
'''

def rk4_step(func, x, y, h, E):
    #
    # e.g. func = rhs, which takes in [psi, u] and outputs [u, 2*(V(x) - E)*psi]
    # x is some array of equally spaced values with some length N+1
    # y is a (N+1)x2 array
    # h is the step size, x[1] - x[0]. This is why it's important that x is equally spaced
    # E is our energy level (in rhs - this may change for other functions)
    #
    # NOTE: y is a 2-vector [???]! kn is also a 2-vector!
    k1 = func(x,       y,            E)
    # first step: uses initial x and y, input into function (in this case rhs of TISE)
    k2 = func(x + h/2, y + h/2*k1,   E)
    # second step: solves TISE rhs half a step later with y's extra half step scaled by k1
    k3 = func(x + h/2, y + h/2*k2,   E)
    # third step: solves TISE rhs at same half step later as step 2, but with y's extra half step scaled by k2
    k4 = func(x + h,   y + h*k3,     E)
    # fourth step: finally gets to next step x, with y's extra full step then scaled by k3
    return y + h/6*(k1 + 2*k2 + 2*k3 + k4)
    # NOTE: both entries in y, psi and u, are affected by h/6*(...)

def solve_tise(E, L=30.0, N=3000, psi0=0.0, u0=1.0):
    # green numbers are defaults - can be overridden
    x = np.linspace(0, L, N + 1)
    # create (N+1)x1 array from 0 to L, equally spaced
    h = x[1] - x[0]
    # define step size dynamically based on x, which is based on L and N. Float.
    y = np.zeros((N + 1, 2))
    # create (N+1)x2 matrix of zeros
    y[0] = [psi0, u0]
    # set initial values of y - we'll replace the zeros in y with values recursively
    for i in range(N):
        y[i+1] = rk4_step(rhs, x[i], y[i], h, E)
        # perform rk4 step on previous y[i] to obtain y[i+1]
    return x, y[:, 0], y[:, 1]
    # returns x, the first row of y, and the second row of y

