import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import brentq
from scipy.integrate import simpson

L = 1.0   # width of the box (walls at x = 0 and x = L)


# potential: zero inside the box
def V(x):
    return 0.0


def rhs(x, y, E):
    psi, u = y
    return np.array([u, 2*(V(x) - E)*psi])


def rk4_step(func, x, y, h, E):
    k1 = func(x,       y,            E)
    k2 = func(x + h/2, y + h/2*k1,   E)
    k3 = func(x + h/2, y + h/2*k2,   E)
    k4 = func(x + h,   y + h*k3,     E)
    return y + h/6*(k1 + 2*k2 + 2*k3 + k4)


def solve_tise(E, L=L, N=1000, psi0=0.0, u0=1.0):
    x = np.linspace(0, L, N + 1)
    h = x[1] - x[0]
    y = np.zeros((N + 1, 2))
    y[0] = [psi0, u0]
    for i in range(N):
        y[i+1] = rk4_step(rhs, x[i], y[i], h, E)
    return x, y[:, 0], y[:, 1]


# ---------- psi at the right wall, as a function of E ----------
def f(E):
    x, psi, u = solve_tise(E)
    return psi[-1]


# ---------- scan E and find sign changes ----------
Es = np.linspace(0.5, 200, 500)
fs = np.array([f(E) for E in Es])

roots = []
for i in range(len(Es) - 1):
    if fs[i] * fs[i+1] < 0:
        roots.append(brentq(f, Es[i], Es[i+1]))

# exact energies for comparison: E_n = n^2 pi^2 / (2 L^2)
exact = [(n*np.pi)**2 / (2*L**2) for n in range(1, len(roots) + 1)]
print("Numerical:", roots)
